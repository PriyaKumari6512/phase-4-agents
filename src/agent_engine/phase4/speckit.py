"""spec-kit without a shell.

The task-breakdown pack ships github/spec-kit 1.3.0's own skills (speckit-specify, -plan, -tasks, -analyze)
unchanged. Those skills call four bash scripts under .specify/scripts/bash/ that only resolve paths, copy a
template and print JSON. Agents here have no shell, so `run_script` reproduces those scripts' JSON output in
Python, and `init` lays out the .specify/ folder spec-kit expects, inside the project folder:

  outputs/<project>/                 <- spec-kit's REPO_ROOT
    .specify/init-options.json
    .specify/memory/constitution.md  <- rendered from phase4/project.json
    .specify/templates/*.md          <- spec-kit 1.3.0 core templates
    specs/NNN-short-name/            <- one folder per feature (spec.md, plan.md, tasks.md, ...)

The feature directory is always passed explicitly (spec-kit's SPECIFY_FEATURE_DIRECTORY), never read from
.specify/feature.json, so several features can be specified in parallel without racing on that file.
"""

from __future__ import annotations

import json
import re
import shlex
from pathlib import Path

from jinja2 import Template

from agent_engine import perf
from agent_engine.phase4 import files
from agent_engine.phase4.contracts import ProjectSettings

ASSETS = Path(__file__).resolve().parent / "speckit_assets"
SPECKIT_VERSION = "1.3.0"
TEMPLATE_NAMES = ("spec-template", "plan-template", "tasks-template", "checklist-template", "constitution-template")
FEATURE_DIR_RE = re.compile(r"^specs/[0-9]{3}-[a-z0-9][a-z0-9-]*$")
SCRIPTS = ("resolve-template", "check-prerequisites", "setup-plan", "setup-tasks")

CONSTITUTION = Template("""# {{ project_name }} Constitution

## Core Principles

### I. Tests First for Business Logic
Business logic is covered by automated tests written before or with the implementation. Every user story has an
independent test.

### II. Observability
Every service emits structured logs, metrics and traces (OpenTelemetry). New endpoints include health checks.

### III. Security Baseline
No secrets in code or configuration files. Authentication and authorization changes require explicit review.
Inputs are validated at boundaries.

### IV. Traceability
Every requirement and user story keeps its source requirement ids from prd.md. Every task names the exact file
paths it changes.

### V. Simplicity
Prefer the smallest design that satisfies the requirements; no speculative abstractions.

## Technology Constraints
The system architecture is defined in `architecture.md` at the repository root; plans must follow it.
{% if code_repos %}Code repositories: {{ code_repos | join(", ") }}.
{% endif %}
## Definition of Done
{% for d in dod %}- {{ d }}
{% endfor %}
## Governance
This constitution is generated by PDLC Phase 4 from phase4/project.json. Amendments go through the project's normal
review process.

**Version**: 1.0.0
""")


def init(project: str) -> str:
    """Initialize missing spec-kit assets; preserve project-reviewed overrides."""
    settings = files.read_json(project, files.PROJECT_SETTINGS, ProjectSettings)
    files.write_json(project, ".specify/init-options.json", {
        "ai": "deepagents", "ai_skills": True, "feature_numbering": "sequential", "here": True,
        "script": "phase4_speckit_script", "speckit_version": SPECKIT_VERSION})
    for name in TEMPLATE_NAMES:
        src = ASSETS / "templates" / f"{name}.md"
        if not files.exists(project, f".specify/templates/{name}.md"):
            files.write_text(project, f".specify/templates/{name}.md", src.read_text(encoding="utf-8"))
    if not files.exists(project, ".specify/memory/constitution.md"):
        files.write_text(project, ".specify/memory/constitution.md", CONSTITUTION.render(
            project_name=settings.project_name, code_repos=settings.code_repos, dod=settings.definition_of_done))
    files.write_json(project, ".specify/engine-policy.json", {
        "speckit_version": SPECKIT_VERSION,
        "constitution_origin": "Engine defaults initialize missing constitution; project amendments are preserved.",
        "default_principles": ["tests for business logic and independent story tests", "OpenTelemetry observability and endpoint health checks",
                               "security review and validated inputs", "requirement traceability", "smallest sufficient design"],
        "review_required": "These are engine policy defaults, not claims extracted from the PRD. Resolve policy/source conflicts explicitly.",
        "template_policy": "Existing project templates are preserved; automatic migration is not performed."})
    (files.project_dir(project) / "specs").mkdir(exist_ok=True)
    existing = sorted(p.name for p in (files.project_dir(project) / "specs").iterdir() if p.is_dir())
    return json.dumps({"REPO_ROOT": files.virtual_root(project),
                       "CONSTITUTION": files.virtual(project, ".specify/memory/constitution.md"),
                       "EXISTING_FEATURE_DIRS": existing})


def _template(project: str, name: str) -> tuple[str, str]:
    """Project override (.specify/templates/<name>.md, written by init) first, then the shipped core template."""
    if name not in TEMPLATE_NAMES:
        raise files.ProjectError(f"Template '{name}' was not found (known: {', '.join(TEMPLATE_NAMES)})")
    rel = f".specify/templates/{name}.md"
    if files.exists(project, rel):
        return rel, files.read_text(project, rel)
    return rel, (ASSETS / "templates" / f"{name}.md").read_text(encoding="utf-8")


def _feature(project: str, feature_dir: str) -> dict:
    feature_dir = (feature_dir or "").strip().strip("/")
    if not FEATURE_DIR_RE.fullmatch(feature_dir):
        raise files.ProjectError(
            f"ERROR: Feature directory not found. Pass feature_directory like 'specs/001-user-auth' (got {feature_dir!r}).")
    v = lambda rel: files.virtual(project, rel)  # noqa: E731
    return {"REPO_ROOT": files.virtual_root(project).rstrip("/"), "BRANCH": feature_dir.split("/", 1)[1], "FEATURE_DIR": v(feature_dir),
            "FEATURE_SPEC": v(f"{feature_dir}/spec.md"), "IMPL_PLAN": v(f"{feature_dir}/plan.md"),
            "TASKS": v(f"{feature_dir}/tasks.md"), "_rel": feature_dir}


def _available_docs(project: str, rel: str, include_tasks: bool) -> list[str]:
    root = files.path(project, rel)
    docs = [n for n in ("research.md", "data-model.md") if (root / n).is_file()]
    contracts = root / "contracts"
    if contracts.is_dir() and any(contracts.iterdir()):
        docs.append("contracts/")
    if (root / "quickstart.md").is_file():
        docs.append("quickstart.md")
    if include_tasks and (root / "tasks.md").is_file():
        docs.append("tasks.md")
    return docs


def run_script(project: str, script: str, args: str = "", feature_directory: str = "") -> str:
    """Python stand-in for `.specify/scripts/bash/<script>.sh <args>`: same JSON keys, same errors."""
    script = script.strip().removesuffix(".sh").rsplit("/", 1)[-1]
    perf.event("speckit_script", script, feature_directory=(feature_directory or "").strip().strip("/")[:80])
    if script not in SCRIPTS:
        raise files.ProjectError(f"unknown spec-kit script {script!r}; available: {', '.join(SCRIPTS)}")
    argv = shlex.split(args or "")
    flags = {a for a in argv if a.startswith("--")}
    if script == "resolve-template":
        names = [a for a in argv if not a.startswith("--")]
        if len(names) != 1:
            raise files.ProjectError("ERROR: Template name is required")
        _, content = _template(project, names[0])
        return json.dumps({"TEMPLATE_NAME": names[0], "TEMPLATE_CONTENT": content})

    f = _feature(project, feature_directory)
    rel = f.pop("_rel")
    root = files.path(project, rel)
    if script == "check-prerequisites":
        if "--paths-only" in flags:
            return json.dumps(f)
        if not root.is_dir():
            raise files.ProjectError(f"ERROR: Feature directory not found: {f['FEATURE_DIR']}. Run /speckit-specify first.")
        plan = root / "plan.md"
        if not plan.is_file() or plan.stat().st_size == 0:
            raise files.ProjectError(f"ERROR: plan.md not found or empty in {f['FEATURE_DIR']}. Run /speckit-plan first.")
        if "--require-spec" in flags and not (root / "spec.md").is_file():
            raise files.ProjectError(f"ERROR: spec.md not found in {f['FEATURE_DIR']}. Run /speckit-specify first.")
        if "--require-tasks" in flags and not (root / "tasks.md").is_file():
            raise files.ProjectError(f"ERROR: tasks.md not found in {f['FEATURE_DIR']}. Run /speckit-tasks first.")
        out = {"FEATURE_DIR": f["FEATURE_DIR"],
               "AVAILABLE_DOCS": _available_docs(project, rel, "--include-tasks" in flags)}
        if "--template" in flags:
            name = argv[argv.index("--template") + 1] if argv.index("--template") + 1 < len(argv) else ""
            out["TEMPLATE_CONTENT"] = _template(project, name)[1]
        return json.dumps(out)
    if script == "setup-plan":
        if not (root / "spec.md").is_file():
            raise files.ProjectError(f"ERROR: spec.md not found in {f['FEATURE_DIR']}. Run /speckit-specify first.")
        plan = root / "plan.md"
        if not plan.is_file():
            _, content = _template(project, "plan-template")
            files.write_text(project, f"{rel}/plan.md", content)
        return json.dumps({k: f[k] for k in ("FEATURE_SPEC", "IMPL_PLAN", "FEATURE_DIR", "BRANCH")})
    # setup-tasks
    if not (root / "plan.md").is_file():
        raise files.ProjectError(f"ERROR: plan.md not found in {f['FEATURE_DIR']}. Run /speckit-plan first.")
    if not (root / "spec.md").is_file():
        raise files.ProjectError(f"ERROR: spec.md not found in {f['FEATURE_DIR']}. Run /speckit-specify first.")
    rel_t, content = _template(project, "tasks-template")
    return json.dumps({"FEATURE_DIR": f["FEATURE_DIR"], "AVAILABLE_DOCS": _available_docs(project, rel, False),
                       "TASKS_TEMPLATE": files.virtual(project, rel_t), "TASKS_TEMPLATE_CONTENT": content})
